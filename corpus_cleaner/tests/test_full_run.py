"""Full-run verification tests for the corpus cleaning pipeline.

These tests verify the final output generated by the full pipeline run
against all 5 user-reflow folders. They do NOT re-run the pipeline;
they assert properties of the existing output directory.

Run:
    pytest corpus_cleaner/tests/test_full_run.py -v
"""

