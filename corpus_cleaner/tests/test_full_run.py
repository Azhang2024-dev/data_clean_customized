# ── Output structure tests ──────────────────────────────────────────────────


class TestOutputStructure:
    """Verify the output directory structure exists."""

    def test_output_directory_exists(self, output_path: Path) -> None:
        """Given the pipeline completed, the output directory must exist."""
        assert output_path.is_dir()

    def test_language_subdirs_exist(self, output_path: Path) -> None:
        """Language subdirectories AR/, EN/, FR/, RU/ must exist."""
        for lang in ("AR", "EN", "FR", "RU"):
            assert (output_path / lang).is_dir(), f"{lang}/ missing"

    def test_isolation_subdirs_exist(self, output_path: Path) -> None:
        """Isolation directories must exist."""
        for subdir in ("_tables", "_contaminated", "_duplicates", "_empty"):
            assert (output_path / subdir).is_dir(), f"{subdir}/ missing"

    def test_language_dirs_have_files(self, output_path: Path) -> None:
        """Each language directory must contain renamed .md files."""
        for lang in ("AR", "EN", "FR", "RU"):
            files = list((output_path / lang).glob("*.md"))
            assert len(files) > 0, f"{lang}/ has no .md files"
            # Verify naming convention: {category}_{topic}_{seq:03d}_{S|M|L}.md
            for f in files[:5]:  # spot-check first 5
                name = f.name
                parts = name.rsplit("_", 2)
                assert len(parts) == 3, f"Bad name format: {name}"
                size_bracket = name.rsplit("_", 1)[-1].replace(".md", "")
                assert size_bracket in ("S", "M", "L"), (
                    f"Bad size bracket in {name}: {size_bracket}"
                )

    def test_isolation_dirs_have_files(self, output_path: Path) -> None:
        """Each isolation directory must contain files."""
        isolation_counts = {
            "_tables": 0,
            "_contaminated": 0,
            "_duplicates": 0,
            "_empty": 0,
        }
        for subdir in isolation_counts:
            count = sum(
                1 for _ in (output_path / subdir).rglob("*") if _.is_file()
            )
            isolation_counts[subdir] = count
        # All should have > 0 files
        for subdir, count in isolation_counts.items():
            assert count > 0, f"{subdir}/ has no files"


# ── Report file tests ───────────────────────────────────────────────────────


class TestReportFiles:
    """Verify the three report files exist and are valid."""

    def test_report_xlsx_exists_and_has_six_sheets(
        self, output_path: Path,
    ) -> None:
        """_report.xlsx must exist with exactly 6 worksheets."""
        xlsx_path = output_path / "_report.xlsx"
        assert xlsx_path.is_file(), "_report.xlsx missing"

        wb = openpyxl.load_workbook(str(xlsx_path))
        expected_sheets = {
            "Summary", "FileDetails", "ContaminatedFiles",
            "Duplicates", "BadFiles", "LengthDistribution",
        }
        actual_sheets = set(wb.sheetnames)
        assert actual_sheets == expected_sheets, (
            f"Sheet mismatch: got {actual_sheets}"
        )
        wb.close()

    def test_report_xlsx_has_data(self, output_path: Path) -> None:
        """Each worksheet must have data beyond the header row."""
        xlsx_path = output_path / "_report.xlsx"
        wb = openpyxl.load_workbook(str(xlsx_path))
        for name in wb.sheetnames:
            ws = wb[name]
            assert ws.max_row >= 1, f"{name} sheet is empty"
            if name == "BadFiles":
                # BadFiles may only have header if 0 bad files
                continue
            assert ws.max_row > 1, (
                f"{name} sheet has only header (no data rows)"
            )
        wb.close()

    def test_file_details_has_14_columns(self, output_path: Path) -> None:
        """FileDetails sheet must have exactly 14 columns."""
        xlsx_path = output_path / "_report.xlsx"
        wb = openpyxl.load_workbook(str(xlsx_path))
        ws = wb["FileDetails"]
        assert ws.max_column == 14, (
            f"FileDetails has {ws.max_column} columns, expected 14"
        )
        wb.close()

    def test_summary_txt_exists_and_has_content(
        self, output_path: Path,
    ) -> None:
        """_summary.txt must exist with expected sections."""
        txt_path = output_path / "_summary.txt"
        assert txt_path.is_file(), "_summary.txt missing"

        content = txt_path.read_text(encoding="utf-8")
        expected_sections = [
            "语料清洗报告",
            "总处理文件数",
            "OCR 污染文件",
            "重复组数",
            "按语言统计",
            "按状态统计",
            "按长度",
        ]
        for section in expected_sections:
            assert section in content, f"Missing section: {section}"

    def test_manifest_json_is_valid(self, output_path: Path) -> None:
        """_original_manifest.json must be valid JSON with required keys."""
        manifest_path = output_path / "_original_manifest.json"
        assert manifest_path.is_file(), "_original_manifest.json missing"

        with open(manifest_path, "r", encoding="utf-8") as f:
            manifest = json.load(f)

        assert isinstance(manifest, dict), "Manifest must be a dict"
        assert len(manifest) > 0, "Manifest is empty"

        # Check first entry has required keys
        first_entry = next(iter(manifest.values()))
        required_keys = {"new_name", "category", "primary_lang",
                         "length_bracket", "status"}
        assert required_keys.issubset(set(first_entry.keys())), (
            f"Missing keys: {required_keys - set(first_entry.keys())}"
        )


# ── Data integrity tests ────────────────────────────────────────────────────


class TestDataIntegrity:
    """Verify the output data is internally consistent."""

    def test_file_counts_are_reasonable(self, output_path: Path) -> None:
        """Total files in output should be in a reasonable range."""
        total = sum(
            1 for _ in output_path.rglob("*") if _.is_file()
            and _.parent.name != "__pycache__"
        )
        # Expected ~3100-3300 files (reports + 3280 source files minus overlap)
        assert 2800 <= total <= 3500, (
            f"Total files {total} outside expected range [2800, 3500]"
        )

    def test_passed_files_total(self, output_path: Path) -> None:
        """Sum of language dir files should be close to ~2170."""
        total = 0
        for lang in ("AR", "EN", "FR", "RU"):
            total += sum(
                1 for _ in (output_path / lang).glob("*.md")
            )
        assert 2000 <= total <= 2400, (
            f"Passed files {total} outside expected range [2000, 2400]"
        )

    def test_no_empty_language_dirs(self, output_path: Path) -> None:
        """Every language dir must have a reasonable number of files."""
        lang_expected = {
            "AR": (200, 500),    # ~418 input, some lost to filtering
            "EN": (100, 400),    # ~255 input
            "FR": (600, 1200),   # ~1448 input (1246 + 200)
            "RU": (500, 1000),   # ~140 input, but auto-discovery found more
        }
        for lang, (lo, hi) in lang_expected.items():
            count = sum(
                1 for _ in (output_path / lang).glob("*.md")
            )
            assert lo <= count <= hi, (
                f"{lang}/ has {count} files, expected [{lo}, {hi}]"
            )

    def test_manifest_entries_match_passed_files(
        self, output_path: Path,
    ) -> None:
        """Manifest ok entries count should be close to passed file count."""
        manifest_path = output_path / "_original_manifest.json"
        with open(manifest_path, "r", encoding="utf-8") as f:
            manifest = json.load(f)

        ok_count = sum(
            1 for v in manifest.values() if v.get("status") == "ok"
        )
        passed_count = 0
        for lang in ("AR", "EN", "FR", "RU"):
            passed_count += sum(
                1 for _ in (output_path / lang).glob("*.md")
            )

        # Manifest uses original_name as JSON keys — duplicate names
        # from different source folders collide (one overwrites the other).
        # Total manifest entries (2965) < total files (3280) confirms this.
        # Allow discrepancy up to the collision budget (~315).
        diff = abs(ok_count - passed_count)
        assert diff <= 350, (
            f"Manifest ok entries ({ok_count}) vs passed files "
            f"({passed_count}) differ by {diff} (key collision budget: 350)"
        )

    def test_summary_stats_are_consistent(self, output_path: Path) -> None:
        """Stats in _summary.txt should add up correctly."""
        txt_path = output_path / "_summary.txt"
        content = txt_path.read_text(encoding="utf-8")

        # Parse key values from summary
        import re
        total_match = re.search(r"总处理文件数:\s*(\d+)", content)
        ok_match = re.search(r"ok:\s*(\d+)", content)
        table_match = re.search(r"table:\s*(\d+)", content)
        cont_match = re.search(r"contaminated:\s*(\d+)", content)
        dup_match = re.search(r"duplicate:\s*(\d+)", content)
        empty_match = re.search(r"empty:\s*(\d+)", content)

        assert total_match, "Missing total count"
        total = int(total_match.group(1))

        # Status counts
        ok = int(ok_match.group(1)) if ok_match else 0
        table = int(table_match.group(1)) if table_match else 0
        cont = int(cont_match.group(1)) if cont_match else 0
        dup = int(dup_match.group(1)) if dup_match else 0
        empty = int(empty_match.group(1)) if empty_match else 0

        status_sum = ok + table + cont + dup + empty
        assert status_sum == total, (
            f"Status sum {status_sum} != total {total}"
        )

    def test_file_naming_convention(self, output_path: Path) -> None:
        """All renamed files must follow {category}_{topic}_{seq:03d}_{S|M|L}.md."""
        import re
        pattern = re.compile(
            r"^(exam|tutorial|book|lecture|short|table|misc)_"
            r".+_"
            r"\d{3}_"
            r"[SML]\.md$"
        )
        bad_names = []
        for lang in ("AR", "EN", "FR", "RU"):
            for f in (output_path / lang).glob("*.md"):
                if not pattern.match(f.name):
                    bad_names.append(str(f.relative_to(output_path)))

        assert len(bad_names) == 0, (
            f"{len(bad_names)} files have bad names: {bad_names[:10]}"
        )
